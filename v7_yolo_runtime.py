def file_hash(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def atomic_json(path, value):
    path = Path(path)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, allow_nan=False))
    temporary.replace(path)


def require_identity(path, identity):
    path = Path(path)
    if path.exists():
        if json.loads(path.read_text()) != identity:
            raise ValueError(f"Provenance mismatch: {path}. Use a new run directory.")
    else:
        atomic_json(path, identity)


def prepare_dataset(ns, plan, directory):
    """Keep distinct annotator targets, sharing their physical source JPEGs."""
    data = directory / "yolo_dataset"
    records = fold_records(plan, ns["records_by_name"])
    height, width = ns["FULL_SHAPE"]
    for phase, label in [("train", "train"), ("tune", "val")]:
        images, labels = data / "images" / label, data / "labels" / label
        images.mkdir(parents=True, exist_ok=True)
        labels.mkdir(parents=True, exist_ok=True)
        for index, record in enumerate(records[phase]):
            stem = f'{Path(record["file_name"]).stem}__annotation{index}'
            source = ns["train_lookup"][record["file_name"]].resolve()
            destination = images / f"{stem}.jpeg"
            if not destination.exists():
                destination.symlink_to(source)
            elif destination.resolve() != source:
                raise ValueError(f"Training image link differs: {destination}")
            lines = []
            for annotation in ns["annotations_by_id"][record["id"]]:
                polygons = annotation["segmentation"]
                if not isinstance(polygons, list) or len(polygons) != 1:
                    raise ValueError("YOLO conversion requires one polygon per instance.")
                points = np.asarray(polygons[0], dtype=np.float64)
                if points.size < 6 or points.size % 2 or not np.isfinite(points).all():
                    raise ValueError(f'Invalid polygon {annotation["id"]}')
                points = points.reshape(-1, 2)
                if np.any(points < 0) or np.any(points > [width, height]):
                    raise ValueError(f'Out-of-bounds polygon {annotation["id"]}')
                lines.append("0 " + " ".join(
                    f"{value:.8f}" for value in (points / [width, height]).ravel()))
            (labels / f"{stem}.txt").write_text("\n".join(lines) + ("\n" if lines else ""))
    path = data / "data.yaml"
    path.write_text(yaml.safe_dump(dict(
        path=str(data.resolve()), train="images/train", val="images/val",
        names={0: "filament"},
    )))
    return path


def train_detector(ns, plan, shared_plan):
    directory = ns["CV_ROOT"] / f"fold_{plan['fold']}"
    directory.mkdir(parents=True, exist_ok=True)
    identity = dict(plan_sha256=cv_digest(shared_plan), fold=plan["fold"])
    require_identity(directory / "fold_identity.json", identity)
    checkpoint, provenance = directory / "yolo_best.pt", directory / "yolo_provenance.json"
    if provenance.exists():
        saved = json.loads(provenance.read_text())
        if saved["identity"] != identity or saved["sha256"] != file_hash(checkpoint):
            raise ValueError("Saved detector checkpoint provenance mismatch.")
        print(f"Fold {plan['fold']}: reusing verified detector", flush=True)
        return YOLO(str(checkpoint))
    if checkpoint.exists():
        raise ValueError("Checkpoint publication was interrupted; preserve it and inspect provenance.")
    if not torch.cuda.is_available() and not ns["SMOKE_TEST"]:
        raise RuntimeError("Enable a GPU before full training.")
    settings = ns["V7"]
    data = prepare_dataset(ns, plan, directory)
    run = directory / "detector_runs" / "yolo"
    last, best = run / "weights" / "last.pt", run / "weights" / "best.pt"
    completed = False
    if last.exists():
        # Only read checkpoints generated by this identity-checked local run.
        saved = torch.load(last, map_location="cpu", weights_only=False)
        completed = saved["epoch"] < 0 or saved["epoch"] + 1 >= settings["epochs"]
        del saved
    started = time.monotonic()
    if not completed:
        if last.exists():
            print(f"Fold {plan['fold']}: resuming last completed YOLO epoch", flush=True)
            model = YOLO(str(last))
            model.train(resume=True, device=ns["YOLO_TRAIN_DEVICE"], workers=settings["workers"])
        else:
            print(f"Fold {plan['fold']}: starting YOLO (no saved epoch)", flush=True)
            model = YOLO(settings["weights"])
            model.train(
                data=str(data), epochs=settings["epochs"], imgsz=settings["image_size"],
                batch=settings["batch_size"], device=ns["YOLO_TRAIN_DEVICE"],
                workers=settings["workers"], patience=settings["patience"], time=None,
                optimizer="AdamW", lr0=settings["learning_rate"], momentum=0.9,
                weight_decay=0.0005, warmup_bias_lr=0.0, seed=ns["CFG"]["seed"],
                single_cls=True, mask_ratio=2, overlap_mask=False,
                hsv_h=0.0, hsv_s=0.0, hsv_v=0.3, fliplr=0.5, flipud=0.0,
                mosaic=0.3, degrees=10.0, scale=0.3, close_mosaic=5,
                cache=False, save=True, save_period=1, plots=False,
                project=str(run.parent), name=run.name, exist_ok=True,
            )
        del model
        gc.collect()
    if not best.is_file():
        raise FileNotFoundError(f"No best detector checkpoint: {best}")
    temporary = checkpoint.with_suffix(".tmp.pt")
    shutil.copyfile(best, temporary)
    temporary.replace(checkpoint)
    atomic_json(provenance, dict(
        identity=identity, sha256=file_hash(checkpoint), settings=settings,
        latest_invocation_seconds=time.monotonic() - started,
        note="Invocation time excludes earlier interrupted attempts; see YOLO results.csv.",
    ))
    return YOLO(str(checkpoint))


def encode_masks(instances):
    return [dict(size=list(rle["size"]), counts=rle["counts"].decode("ascii"))
            for rle in instances]


def decode_masks(items):
    return [dict(size=item["size"], counts=item["counts"].encode("ascii")) for item in items]


def image_manifest(paths):
    if not paths or len({p.stem for p in paths}) != len(paths):
        raise ValueError("Prediction image IDs must be nonempty and unique.")
    return [dict(name=p.name, sha256=file_hash(p)) for p in paths]


def predict_cached(ns, detector, paths, parameters, cache_path, identity):
    """Save each completed inference batch; restart only missing images."""
    paths = list(paths)
    shape = ns["FULL_SHAPE"]
    expected = {p.stem for p in paths}
    cache_identity = dict(
        model=identity, parameters=parameters,
        images_sha256=cv_digest(image_manifest(paths)), shape=list(shape),
    )
    cache_path = Path(cache_path)
    if cache_path.exists():
        cache = json.loads(cache_path.read_text())
        if cache["identity"] != cache_identity:
            raise ValueError(f"Stale prediction cache: {cache_path}")
    else:
        cache = dict(identity=cache_identity, predictions={})
    predictions = cache["predictions"]
    if not set(predictions) <= expected:
        raise ValueError("Prediction cache contains unknown image IDs.")
    for items in predictions.values():
        validate_disjoint(decode_masks(items), shape)
    missing = [p for p in paths if p.stem not in predictions]
    batch_size = ns["V7"]["inference_batch"]
    if type(batch_size) is not int or batch_size < 1:
        raise ValueError("inference_batch must be a positive integer.")
    print(f"{cache_path.name}: {len(predictions)}/{len(paths)} saved", flush=True)
    for start in range(0, len(missing), batch_size):
        batch = missing[start:start + batch_size]
        results = detector.predict(
            source=[str(p) for p in batch], batch=batch_size,
            imgsz=ns["V7"]["image_size"], conf=parameters["confidence"],
            device=ns["YOLO_INFERENCE_DEVICE"], agnostic_nms=True, retina_masks=True,
            verbose=False, stream=False,
        )
        if len(results) != len(batch):
            raise ValueError("Detector returned an unexpected batch length.")
        for path, result in zip(batch, results):
            if Path(result.path).resolve() != path.resolve() or tuple(result.orig_shape) != tuple(shape):
                raise ValueError("Detector result path/dimensions differ from its input.")
            instances = []
            if result.masks is not None:
                masks = result.masks.data.cpu().numpy()
                if masks.ndim != 3 or tuple(masks.shape[1:]) != tuple(shape):
                    raise ValueError("Detector masks must retain original image dimensions.")
                if not np.isin(masks, [0, 1]).all():
                    raise ValueError("Detector masks must be finite and binary.")
                instances = [mask_utils.encode(np.asfortranarray(mask.astype(np.uint8)))
                             for mask in masks if mask.any()]
            instances, _ = disjoint_instances(instances, shape, parameters["min_area"])
            validate_disjoint(instances, shape)
            predictions[path.stem] = encode_masks(instances)
        atomic_json(cache_path, cache)
        print(f"{cache_path.name}: {len(predictions)}/{len(paths)} saved", flush=True)
    if set(predictions) != expected:
        raise ValueError("Incomplete inference coverage.")
    return predictions


def score_predictions(ns, names, predictions):
    rows = []
    for name in names:
        instances = decode_masks(predictions[Path(name).stem])
        scores = [ns["local_scores"](instances, ns["gt_rles"](record["id"]))
                  for record in ns["records_by_name"][name]]
        if not scores:
            raise ValueError(f"No annotator sets: {name}")
        rows.append(dict(
            filename=name, annotator_sets=len(scores), instances=len(instances),
            **{key: float(np.mean([score[key] for score in scores])) for key in scores[0]},
        ))
    if not rows:
        raise ValueError("No evaluation images.")
    means = {key: float(np.mean([row[key] for row in rows]))
             for key in rows[0] if key not in ["filename", "annotator_sets"]}
    return means, rows


def calibrate(ns, detector, plan, identity):
    directory = ns["CV_ROOT"] / f"fold_{plan['fold']}"
    path = directory / "calibration.json"
    if path.exists():
        saved = json.loads(path.read_text())
        if saved["identity"] != identity:
            raise ValueError("Calibration provenance mismatch.")
        return saved
    names = plan["splits"]["tune"][:ns["V7"]["tuning_images"]]
    trials = []
    for confidence in ns["V7"]["confidences"]:
        for min_area in ns["V7"]["min_areas"]:
            parameters = dict(mode="yolo", confidence=confidence, min_area=min_area)
            predictions = predict_cached(
                ns, detector, [ns["train_lookup"][name] for name in names], parameters,
                directory / f"tune_{confidence}_{min_area}.json", identity,
            )
            means, _ = score_predictions(ns, names, predictions)
            trials.append(dict(parameters=parameters, scores=means))
    selected = max(trials, key=lambda trial: trial["scores"]["pq"])
    result = dict(identity=identity, selected=selected, trials=trials, tuning_names=names)
    atomic_json(path, result)
    print("TUNING ONLY, not independent performance:", selected, flush=True)
    return result


def fold_model_identity(ns, plan, shared_plan):
    checkpoint = ns["CV_ROOT"] / f"fold_{plan['fold']}" / "yolo_best.pt"
    return dict(plan_sha256=cv_digest(shared_plan), fold=plan["fold"],
                checkpoint_sha256=file_hash(checkpoint))


def run_fold(ns, plan, shared_plan):
    directory = ns["CV_ROOT"] / f"fold_{plan['fold']}"
    path = directory / "fold_result.json"
    if path.exists():
        result = json.loads(path.read_text())
        validate_fold_result(result, plan, cv_digest(shared_plan))
        identity = fold_model_identity(ns, plan, shared_plan)
        if result["checkpoint_hashes"] != {"yolo_best.pt": identity["checkpoint_sha256"]}:
            raise ValueError("Completed fold checkpoint changed.")
        print(f"Fold {plan['fold']}: reusing completed outer evaluation", flush=True)
        return result
    detector = train_detector(ns, plan, shared_plan)
    try:
        identity = fold_model_identity(ns, plan, shared_plan)
        calibration = calibrate(ns, detector, plan, identity)
        parameters = calibration["selected"]["parameters"]
        names = plan["splits"]["holdout"]
        predictions = predict_cached(
            ns, detector, [ns["train_lookup"][name] for name in names], parameters,
            directory / "outer_predictions.json", identity,
        )
        means, rows = score_predictions(ns, names, predictions)
        result = dict(
            fold=plan["fold"], plan_sha256=cv_digest(shared_plan), status="complete",
            smoke_test=ns["SMOKE_TEST"],
            checkpoint_hashes={"yolo_best.pt": identity["checkpoint_sha256"]},
            selected_parameters=parameters, inner_selected_scores=calibration["selected"]["scores"],
            outer_mean=means, outer_rows=rows,
        )
        validate_fold_result(result, plan, cv_digest(shared_plan))
        atomic_json(path, result)
        return result
    finally:
        del detector
        gc.collect()
        if torch.cuda.is_available():
            torch.cuda.empty_cache()


def write_submission(ns, shared_plan, predictions, results):
    """Validate the exact CSV read back from disk and publish its checksum last."""
    if ns["SMOKE_TEST"] or shared_plan["smoke_test"]:
        raise ValueError("Smoke experiments cannot export competition submissions.")
    root, shape = ns["CV_ROOT"], ns["FULL_SHAPE"]
    paths = ns["test_paths"]
    names = {path.stem for path in paths}
    if len(predictions) != 5 or any(set(fold) != names for fold in predictions):
        raise ValueError("Export requires complete test coverage from exactly five models.")
    rows = []
    for index, path in enumerate(paths):
        per_fold = [decode_masks(fold[path.stem]) for fold in predictions]
        instances = fuse_fold_instances(per_fold, shape)
        instances, _ = disjoint_instances(instances, shape, ENSEMBLE_POLICY["min_area"])
        validate_disjoint(instances, shape)
        rows.extend(dict(filament_id=f"{path.stem}_{i}", segmentation_rle=rle["counts"].decode("ascii"))
                    for i, rle in enumerate(instances, 1))
        print(f"Fusion: {index + 1}/{len(paths)}", flush=True)
    validate_submission_rows(rows, names, shape)
    destination = root / "submission_V7_yolo_only.csv"
    temporary = destination.with_suffix(".tmp.csv")
    with temporary.open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=SUBMISSION_FIELDS)
        writer.writeheader()
        writer.writerows(rows)
    with temporary.open(newline="") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames != SUBMISSION_FIELDS:
            raise ValueError("Written CSV columns differ.")
        readback = list(reader)
    if readback != rows:
        raise ValueError("Written CSV differs from generated predictions.")
    audit = validate_submission_rows(readback, names, shape)
    digest = file_hash(temporary)
    temporary.replace(destination)
    atomic_json(root / "ensemble_audit.json", dict(
        run_name=root.name, architecture="YOLO-only; no crop refiner",
        plan_sha256=cv_digest(shared_plan), policy=ENSEMBLE_POLICY,
        test_manifest_sha256=cv_digest(image_manifest(paths)),
        folds=[dict(fold=r["fold"], hashes=r["checkpoint_hashes"],
                    parameters=r["selected_parameters"]) for r in results],
        validation=audit, submission_filename=destination.name, submission_sha256=digest,
    ))
    if file_hash(destination) != digest:
        raise ValueError("Final submission checksum mismatch.")
    print("FINAL V7 CSV VERIFIED:", destination, "\nSHA256:", digest, "\nVALIDATION:", audit,
          "\nNo upload performed. Match this hash before manual submission.", flush=True)
    return destination


def export_ensemble(ns, plans, shared_plan):
    if ns["SMOKE_TEST"] or shared_plan["smoke_test"]:
        raise ValueError("Smoke experiments cannot export competition submissions.")
    if sorted(plan["fold"] for plan in plans) != list(range(5)):
        raise ValueError("Five unique fold plans are required.")
    plans = sorted(plans, key=lambda plan: plan["fold"])
    results, predictions = [], []
    for plan in plans:
        directory = ns["CV_ROOT"] / f"fold_{plan['fold']}"
        result = json.loads((directory / "fold_result.json").read_text())
        validate_fold_result(result, plan, cv_digest(shared_plan))
        identity = fold_model_identity(ns, plan, shared_plan)
        if result["checkpoint_hashes"] != {"yolo_best.pt": identity["checkpoint_sha256"]}:
            raise ValueError("Export checkpoint differs from evaluated model.")
        calibration = json.loads((directory / "calibration.json").read_text())
        if (calibration["identity"] != identity
                or calibration["selected"]["parameters"] != result["selected_parameters"]):
            raise ValueError("Export calibration differs from evaluated settings.")
        detector = YOLO(str(directory / "yolo_best.pt"))
        try:
            predictions.append(predict_cached(
                ns, detector, ns["test_paths"], result["selected_parameters"],
                directory / "test_predictions.json", identity,
            ))
            results.append(result)
        finally:
            del detector
            gc.collect()
            if torch.cuda.is_available():
                torch.cuda.empty_cache()
    return write_submission(ns, shared_plan, predictions, results)
